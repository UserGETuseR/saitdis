// «Совет Деда дня» на экране практик берёт общий список.
// Дополняем его, а не перезаписываем: советы из data.practices.js остаются.
window.DED_WISDOM = [
  ...(window.DED_WISDOM || []),
  ...Object.values(window.DED_WISDOM_BY_TOPIC).flat(),
];

window.Wisdom = (function () {
  const DAY_MS = 86400000;

  // Мудрость дня: стабильна в течение суток, чтобы интерфейс не «мерцал»
  // при каждом переходе между экранами.
  function ofTheDay(topic = "welcome", offset = 0) {
    const list = window.DED_WISDOM_BY_TOPIC[topic] || window.DED_WISDOM_BY_TOPIC.welcome || [];
    if (!list.length) return null;
    const day = Math.floor(Date.now() / DAY_MS);
    return list[(day + offset) % list.length];
  }

  // Стабильная мудрость для конкретной сущности (сорта чая, гриба):
  // один и тот же чай всегда получает одну и ту же фразу.
  function forKey(topic, key) {
    const list = window.DED_WISDOM_BY_TOPIC[topic] || [];
    if (!list.length) return null;
    const seed = String(key || "").split("").reduce((sum, char) => sum + char.charCodeAt(0), 0);
    return list[seed % list.length];
  }

  function all(topic) {
    return (window.DED_WISDOM_BY_TOPIC[topic] || []).slice();
  }

  return { ofTheDay, forKey, all };
})();
